const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const source = path.join(__dirname, '../src/protocol/nativePlayback.ts');
const loaded = new Module(source, module);
loaded.filename = source;
loaded.require = key => key === './audioV2' ? { AudioCodec: { OPUS: 1 } } : require(key);
loaded._compile(ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, source);
const { NativePlayback } = loaded.exports;
const binding = { captureSessionId: {value: 'capture'}, voiceSessionId: {value: 'voice'}, captureEpoch: 7n };
const offer = id => ({binding, responseId: {value: id}, generation: 1n, incremental: true, preSkipSamples: 156,
 audioSpec: {codec: 1, sampleRateHz: 24000, channelCount: 1, frameDuration: {seconds: 0n, nanos: 20000000}}});
const packet = (id, n) => ({ responseId: {value: id}, generation: 1n, sequence: BigInt(n), opusPayload: new Uint8Array([1,2]), finalPacket: false });
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
 const calls = [], acks = [], errors = [];
 const port = Object.fromEntries(['beginResponse','appendResponse','finishResponse','cancelResponse'].map(key => [key, async (...args) => calls.push([key, ...args])]));
 const playback = new NativePlayback(binding, port, bytes => Buffer.from(bytes).toString('base64'), ack => acks.push(ack), error => errors.push(error));
 playback.open(offer('one')); playback.append(packet('one',0)); playback.append(packet('one',1));
 await flush();
 assert.deepEqual(calls.map(c => c[0]), ['beginResponse','appendResponse','appendResponse']);
 assert.equal(calls[0][1].preSkipSamples,156);
 playback.progress({responseId:'one',generation:1,captureEpoch:7,state:'progress',renderedSamples:324,bufferedSamples:480,monotonicTimestampMs:12345});
 playback.finish({binding, responseId:{value:'one'}, generation:1n,totalSamples:604n});
 await flush(); assert.equal(calls.at(-1)[1].totalSamples,604);
 playback.progress({responseId:'one',generation:1,captureEpoch:7,state:'done',renderedSamples:604,bufferedSamples:0,monotonicTimestampMs:12400});
 assert.equal(acks.at(-1).renderedSamples,604);
 playback.open(offer('one')); await flush(); assert.equal(calls.length,4,'duplicate offer cannot replay speech');
 playback.open(offer('two')); playback.append(packet('two',1)); await flush();
 assert.equal(acks.at(-1).state,'failed','invalid sequence is explicitly rejected');
 assert.ok(!calls.some(c => c[0]==='appendResponse' && c[1].responseId==='two'));
 playback.open(offer('three')); for(let i=0;i<101;i++) playback.append(packet('three',i)); await flush();
 assert.equal(errors.at(-1).message,'Invalid playback order or buffer limit');
 playback.open(offer('four')); playback.close(); await flush();
 assert.ok(!calls.some(c => c[0]==='beginResponse' && c[1].responseId==='four'),'close fences queued native operations');
 const failure = new NativePlayback(binding,{...port,beginResponse:async()=>{throw new Error('decoder unavailable')}},()=>'',ack=>acks.push(ack),error=>errors.push(error));
 failure.open(offer('broken')); await flush();
 assert.equal(acks.at(-1).state,'failed'); assert.equal(acks.at(-1).monotonicTimestampMs,0,'never invent a native clock reading');
 assert.ok(calls.some(c=>c[0]==='cancelResponse' && c[1]==='broken'));
 console.log('native incremental playback protocol tests passed');
})().catch(error=>{console.error(error);process.exitCode=1});
